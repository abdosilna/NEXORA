// Complete beginner & intermediate Programming Academy curriculum for Python, JavaScript, HTML, CSS, and Node.js.
// Every lesson provides: theory explanation, working code block, expected output, common mistakes,
// a practical hands-on exercise, and multi-question quiz items.

function buildProgrammingLesson({
  courseSlug,
  slug,
  order,
  lessonType = 'lesson',
  title,
  explanation,
  codeLang,
  code,
  expectedOutput,
  commonMistakes = [],
  practiceTask,
  examples = [],
  exercises = [],
}) {
  const sections = [
    `📖 *الشرح التعليمي:*\n${explanation.trim()}`,
    `💻 *مثال برمجي تطبيقي:*\n\`\`\`${codeLang}\n${code.trim()}\n\`\`\``,
    `📤 *المخرجات / النتيجة المتوقعة:*\n${expectedOutput.trim()}`,
  ];

  if (commonMistakes.length) {
    sections.push(`⚠️ *أخطاء شائعة يجب تجنبها:*\n${commonMistakes.map((m) => `• ${m}`).join('\n')}`);
  }

  if (practiceTask) {
    sections.push(`✍️ *تمرين عملي مقترح:*\n${practiceTask.trim()}`);
  }

  return {
    courseSlug,
    slug,
    lesson_type: lessonType,
    title_ar: title,
    content_ar: sections.join('\n\n'),
    examples,
    pronunciation_text: '',
    pronunciation_lang: 'en',
    sort_order: order,
    exercises,
  };
}

